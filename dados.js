/* =========================================================
   💰 FORMATAR PREÇO
========================================================= */

function precoBRL(valor) {

    const numero = Number(valor);

    if (
        !Number.isFinite(numero) ||
        numero <= 0
    ) {
        return "Preço não informado";
    }

    return numero.toLocaleString(
        "pt-BR",
        {
            style: "currency",
            currency: "BRL"
        }
    );

}


/* =========================================================
   🏆 CALCULAR NOTA
========================================================= */

function calcularNota(produto) {

    const notas = [

        Number(produto.desempenho),
        Number(produto.jogos),
        Number(produto.trabalho),
        Number(produto.qualidade)

    ].filter(
        numero => Number.isFinite(numero)
    );


    if (notas.length === 0) {

        return 0;

    }


    const media =
        notas.reduce(
            (total, numero) =>
                total + numero,
            0
        ) / notas.length;


    return Math.round(media);

}


/* =========================================================
   🏆 ORDENAR POR RANKING
========================================================= */

function ordenarPorRanking(lista) {

    return [...lista].sort(
        (a, b) =>
            calcularNota(b) -
            calcularNota(a)
    );

}


/* =========================================================
   🔎 PESQUISAR
========================================================= */

function pesquisarProdutos(
    lista,
    termo
) {

    const busca =
        String(termo || "")
            .toLowerCase()
            .trim()
            .normalize("NFD")
            .replace(
                /[\u0300-\u036f]/g,
                ""
            );


    if (!busca) {

        return [...lista];

    }


    return lista.filter(
        produto => {

            const texto = [

                produto.nome,
                produto.marca,
                produto.categoria,
                produto.processador,
                produto.video,
                produto.ram,
                produto.armazenamento

            ]
            .map(
                valor =>
                    String(valor || "")
            )
            .join(" ")
            .toLowerCase()
            .normalize("NFD")
            .replace(
                /[\u0300-\u036f]/g,
                ""
            );


            return texto.includes(busca);

        }
    );

}


